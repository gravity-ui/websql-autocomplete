import {ParserRuleContext, TerminalNode} from 'antlr4ng';

import {IStatementsVisitor, StatementPosition} from '../../shared/index.js';
import {getStatementEndIndex} from '../../shared/extract-statement-positions-from-query.js';
import {
    Batch_level_statementContext,
    Execute_body_batchContext,
    Sql_clausesContext,
} from './generated/TSqlParser.js';
import {TSqlParserVisitor} from './generated/TSqlParserVisitor.js';

export class MsSqlStatementsVisitor
    extends TSqlParserVisitor<unknown>
    implements IStatementsVisitor
{
    statementPositions: StatementPosition[] = [];
    lastTokenIndex = 0;

    // We don't visit children of statements, because procedures, triggers and blocks contain nested statements
    visitSql_clauses = (context: Sql_clausesContext): void => {
        // Linter doesn't like uppercase function names, but this name is generated by ANTLR
        // eslint-disable-next-line new-cap
        this.addStatement(context, context.SEMI());
    };

    visitBatch_level_statement = (context: Batch_level_statementContext): void => {
        this.addStatement(context, null);
    };

    // Batch can start with a procedure call without EXECUTE keyword
    visitExecute_body_batch = (context: Execute_body_batchContext): void => {
        this.addStatement(context, null);
    };

    private addStatement(context: ParserRuleContext, semi: TerminalNode | null): void {
        if (!context.start || !context.stop) {
            return;
        }

        // Empty statement, there is only semicolon
        if (semi && context.getChildCount() === 1) {
            return;
        }

        this.statementPositions.push({
            startIndex: context.start.start,
            endIndex: getStatementEndIndex(context.stop, semi),
        });
        this.lastTokenIndex = semi ? semi.symbol.tokenIndex : context.stop.tokenIndex;
    }
}
